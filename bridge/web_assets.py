def is_public_file_path(public_path):
    """Return whether a path is in the fixed public asset allowlist."""
    return (public_path in STATIC or public_path == "/index.html" or
            any(route.fullmatch(public_path) for route, _ in PUBLIC_FILE_ROUTES))
